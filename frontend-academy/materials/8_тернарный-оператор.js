// 4. Переписать простой if / else

// Если обе ветви лишь присваивают значение одной переменной, тернарная запись часто удобнее. В if для изменяемой переменной нужен let. В тернарной записи результат можно сразу сохранить через const. Проверь, что обе формы дают одинаковый результат и при true, и при false.

