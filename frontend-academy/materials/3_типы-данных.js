/*
1. Число, строка и boolean

Тип описывает, какие данные содержит значение и как над ними работают операции. number — числа, включая целые и дробные; string — текст в кавычках; boolean — ровно true или false, без кавычек. Значение "false" является строкой, а не boolean.

console.log показывает значения, но внешний вид вывода не всегда раскрывает тип. Число 10 и строка "10" могут выглядеть в терминале похоже; нужен typeof.
*/
const numericAge = 21;
const textAge = "21";
const studyingNow = true;
console.log(numericAge);
console.log(textAge);
console.log(studyingNow);

/*
ПОСТРОЧНЫЙ РАЗБОР
Строка 1 хранит number, строка 2 — string, строка 3 — boolean. Строки 4–6 печатают 21, 21 и true. Похожий вывод первых двух строк не делает их значения одинакового типа.
*/

/*
2. typeof возвращает строку с названием типа

typeof — оператор, который сообщает тип выражения. Форма typeof value читает значение; скобки можно использовать для ясности, как typeof (10 + 2). Полученный результат — строка с названием в нижнем регистре: "number", "string", "boolean". Это не имена Number, String и Boolean: с заглавной буквы называются встроенные функции преобразования.

В обычном .js файле одинокая строка typeof value не печатает результат. Чтобы увидеть его в терминале, передай результат в console.log.
*/
const typedName = "Hiraoka";
const typedHeight = 170;
const typedStudent = false;
console.log(typeof typedName);
console.log(typeof typedHeight);
console.log(typeof typedStudent);

/*
ПОСТРОЧНЫЙ РАЗБОР
Строки 1–3 сохраняют три значения. Строка 4 печатает string, строка 5 — number, строка 6 — boolean. typeof не изменяет исходные данные. console.log отвечает только за показ результата.
*/

/*
3. undefined, null и NaN

undefined означает отсутствие присвоенного значения: let pendingValue создаёт переменную, но пока не даёт ей данные. null обычно используют как явную отметку отсутствия значения. Это разные значения; typeof undefined даёт "undefined".

typeof null исторически даёт "object". Это особенность языка, а не доказательство, что null является обычным объектом. NaN — специальное значение number для неудачного числового результата; typeof NaN даёт "number". Тип не доказывает, что значение пригодно для суммы.
*/
let pendingValue;
const emptyValue = null;
const invalidNumber = 0 / 0;
console.log(typeof pendingValue);
console.log(typeof emptyValue);
console.log(typeof invalidNumber);

/*
ПОСТРОЧНЫЙ РАЗБОР
Строка 1 оставляет значение undefined. Строка 2 явно сохраняет null. Строка 3 получает NaN из арифметики урока 2. Строки 4–6 печатают undefined, object и number. Эти три результата нужно объяснять вместе со значениями, а не заучивать только подписи.
*/

/*
4. Неявное преобразование и оператор +

+ работает и как сложение чисел, и как соединение строк — конкатенация. Если один операнд строка, второй в таком примере тоже преобразуется в строку. Поэтому "10" + 5 даёт "105". У - нет операции конкатенации: "10" - 5 преобразует строку в число и даёт 5.

Если строка не представляет число, вычитание может дать NaN. Не исправляй подобный баг сменой оператора наугад: сначала проверь входные значения и их типы. Выражения считаются последовательно с учётом приоритета.
*/
const inputAmount = "10";
const extraAmount = 5;
console.log(inputAmount + extraAmount);
console.log(inputAmount - extraAmount);
console.log("имя" - extraAmount);
console.log(2 + 3 + "4");

/*
ПОСТРОЧНЫЙ РАЗБОР
Строки 1–2 задают string и number. Строка 3 печатает 105 как результат конкатенации. Строка 4 печатает число 5 после преобразования. Строка 5 печатает NaN. Строка 6 сначала складывает 2 + 3 до 5, затем соединяет со строкой "4"; вывод 54.
*/

/*
5. Явные Number, String и Boolean

Явное преобразование записываем встроенным именем и скобками: Number("12") получает числовое значение, String(12) — строковое, Boolean(0) — boolean. Это вызовы готовых встроенных функций; писать свои функции пока не требуется. Значение внутри скобок — вход, результат можно сохранить в const или показать.

Boolean(0) и Boolean("") дают false; Boolean("false") даёт true, поскольку это непустая строка. Это не распознавание слов "true"/"false". Полный разбор логического контекста будет в уроке 7.
*/
const convertedAmount = Number("12");
const convertedLabel = String(12);
const convertedFlag = Boolean(0);
console.log(convertedAmount + 3);
console.log(typeof convertedLabel);
console.log(convertedFlag);
console.log(Boolean("false"));

/*
ПОСТРОЧНЫЙ РАЗБОР
Строка 1 получает число 12, строка 2 — строку "12", строка 3 — false. Строка 4 печатает 15, поскольку складываются числа. Строка 5 печатает string. Строки 6–7 печатают false и true.
*/

/*
6. Преобразование не проверяет бизнес-правила

Number("текст") даёт NaN. Number("") и Number("   ") дают 0: пустое поле может превратиться в ноль без сообщения об ошибке. Преобразование не доказывает, что человек ввёл допустимую цену. Boolean("0") даёт true, поскольку строка не пустая.

typeof помогает найти класс данных, но не проверяет допустимый диапазон, формат имени и конечность числа. Сначала выясняй контракт входа. Проверки условиями начнутся в уроке 4; полноценная валидация развивается позже.
*/
console.log(Number("текст"));
console.log(Number(""));
console.log(Number("   "));
console.log(Boolean("0"));
console.log(typeof Number("текст"));

/*
ПОСТРОЧНЫЙ РАЗБОР
Строка 1 печатает NaN. Строки 2–3 показывают 0 после преобразования пустого текста. Строка 4 печатает true для непустой строки. Строка 5 печатает number даже для NaN: тип и полезность значения различаются.
*/

