// но используем его много раз.



// ==================================================
// 3. ПАРАМЕТРЫ ФУНКЦИИ
// ==================================================


// Функция может получать данные.

// Например:

function greet(name) {

    console.log("Привет, " + name);

}


// name — это параметр функции.


greet("Hiraoka");

greet("Alex");

greet("Anna");


// Результат:

// Привет, Hiraoka
// Привет, Alex
// Привет, Anna



// ==================================================
// 4. ПАРАМЕТР И АРГУМЕНТ
// ==================================================


// Когда создаём функцию:

function sayName(name) {

    console.log(name);

}


// name — параметр


// Когда вызываем:

sayName("Hiraoka");


// "Hiraoka" — аргумент



// Схема:

// function sayName(параметр) {
//
// }


// sayName(аргумент);



// ==================================================
// 5. НЕСКОЛЬКО ПАРАМЕТРОВ
// ==================================================


function introduce(name, age) {

    console.log(
        "Меня зовут " + name + ", мне " + age + " лет"
    );

}


introduce("Hiraoka", 18);


// Результат:

// Меня зовут Hiraoka, мне 18 лет



// ==================================================
// 6. RETURN — ВОЗВРАТ ЗНАЧЕНИЯ
// ==================================================


// Функция может не только выводить данные,
// но и возвращать результат.

// Для этого используется return.


function add(a, b) {

    return a + b;

}


const result = add(5, 3);


console.log(result);


// Результат:

// 8



// Что произошло:

// add(5, 3)
//      ↓
// 5 + 3
//      ↓
// 8
//      ↓
// return
//      ↓
// result



// ==================================================
// 7. console.log VS return
// ==================================================


// console.log просто показывает результат:


function testLog() {

    console.log(10);

}


testLog();


// return отдаёт значение,
// которое можно сохранить:

function testReturn() {

    return 10;

}


const number = testReturn();


console.log(number);



