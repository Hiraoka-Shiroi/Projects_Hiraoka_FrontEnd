// Функция — это блок кода,
// который можно создать один раз
// и запускать сколько угодно раз.

// Например:

function sayHello() {

    console.log("Привет, Hiraoka!");

}


// Пока функция НЕ работает.
// Мы только создали её.

// Чтобы запустить функцию:

sayHello();


// Результат:

// Привет, Hiraoka!


// ==================================================
// 2. ЗАЧЕМ НУЖНЫ ФУНКЦИИ
