// ==================================================

// УРОК 8 — ТЕРНАРНЫЙ ОПЕРАТОР ? :

// ==================================================


// ==================================================

// 1. ЧТО ТАКОЕ ТЕРНАРНЫЙ ОПЕРАТОР

// ==================================================

// Тернарный оператор — короткий способ записать

// простое условие if / else.

// Он используется, когда есть только ДВА варианта:

// если условие true → один результат

// если условие false → другой результат


// Обычный if / else:

const ageExample = 18;

if (ageExample >= 18) {

    console.log("Совершеннолетний");

} else {

    console.log("Несовершеннолетний");

}


// То же самое через тернарный оператор:

const statusExample = ageExample >= 18

    ? "Совершеннолетний"

    : "Несовершеннолетний";

console.log(statusExample);


// ==================================================

// 2. СТРУКТУРА ТЕРНАРНОГО ОПЕРАТОРА

// ==================================================

// Общая форма:

// const переменная = условие ? значение1 : значение2;


// Можно читать так:

// условие ? если true : если false


// ? → отделяет условие от значения для true

// : → отделяет значение для true от значения для false


// Например:

const age = 20;

const result = age >= 18

    ? "Можно войти"

    : "Нельзя войти";

console.log(result);


// Если age >= 18 → result получит "Можно войти"

// Если age < 18 → result получит "Нельзя войти"


// ==================================================

// 3. СРАВНЕНИЕ С IF / ELSE

// ==================================================

// IF / ELSE:

const money = 5000;

if (money >= 3000) {

    console.log("Можно купить");

} else {

    console.log("Нельзя купить");

}


// Тернарный оператор:

const purchase = money >= 3000

    ? "Можно купить"

    : "Нельзя купить";

console.log(purchase);


// Логика одинаковая.

// Тернарный оператор просто записан короче.


// ==================================================

// 4. ТЕРНАРНЫЙ ОПЕРАТОР ВОЗВРАЩАЕТ ЗНАЧЕНИЕ

// ==================================================

// Важное преимущество тернарного оператора:

// результат можно сразу сохранить в переменную.


// Например:

const age2 = 25;

const status = age2 >= 18

    ? "Взрослый"

    : "Ребёнок";

console.log(status);


// status получит строку "Взрослый"


// ==================================================

// 5. ТЕРНАРНЫЙ ОПЕРАТОР И TRUE / FALSE

// ==================================================

const isStudent = true;

const studentStatus = isStudent

    ? "Студент"

    : "Не студент";

console.log(studentStatus);


// isStudent === true

// → "Студент"


// isStudent === false

// → "Не студент"


// ==================================================

// 6. ТЕРНАРНЫЙ ОПЕРАТОР И ЧИСЛА

// ==================================================

const score = 85;

const resultScore = score >= 50

    ? "Сдал"

    : "Не сдал";

console.log(resultScore);


// Если score >= 50 → "Сдал"

// Если score < 50 → "Не сдал"


// ==================================================

// 7. ТЕРНАРНЫЙ ОПЕРАТОР И TRUTHY / FALSY

// ==================================================

// Тернарный оператор тоже проверяет,

// является ли условие true / false.


// Например:

const username = "Hiraoka";

const userStatus = username

    ? "Пользователь найден"

    : "Пользователь не найден";

console.log(userStatus);


// Непустая строка → truthy

// Поэтому результат → "Пользователь найден"


// А здесь:

const password = "";

const passwordStatus = password

    ? "Пароль введён"

    : "Пароль пустой";

console.log(passwordStatus);


// Пустая строка → falsy

// Поэтому результат → "Пароль пустой"


// ==================================================

// 8. КОГДА ИСПОЛЬЗОВАТЬ ТЕРНАРНЫЙ ОПЕРАТОР

// ==================================================

// Тернарный оператор хорошо подходит,

// когда условие простое и имеет ДВА результата.


// Например:

const age3 = 19;

const access = age3 >= 18

    ? "Доступ разрешён"

    : "Доступ запрещён";

console.log(access);


// ==================================================

// 9. КОГДА ЛУЧШЕ ИСПОЛЬЗОВАТЬ IF / ELSE

// ==================================================

// Если условий много, if / else обычно читается лучше.


// Например:

const score2 = 85;

if (score2 >= 90) {

    console.log("Отлично");

} else if (score2 >= 70) {

    console.log("Хорошо");

} else if (score2 >= 50) {

    console.log("Удовлетворительно");

} else {

    console.log("Не сдал");

}


// Для такой логики тернарный оператор становится

// неудобным и плохо читаемым.


// Поэтому:

// 2 варианта → часто удобно использовать ? :

// много вариантов → лучше if / else if / else


// ==================================================

// 10. ВАЖНАЯ ФОРМУЛА

// ==================================================

// Запомни:

// const переменная = условие ? значение1 : значение2;


// Или ещё проще:

// условие ? TRUE : FALSE


// Пример:

// const result = age >= 18 ? "Да" : "Нет";


// Читаем:

// age >= 18 — условие

// ? "Да" — если условие true

// : "Нет" — если условие false


// ==================================================

// ПРАКТИКА

// ==================================================


// --------------------------------------------------

// ЗАДАНИЕ 1 — ВОЗРАСТ

// --------------------------------------------------

// Если возраст 18 или больше:

// "Можно войти"

// Если меньше 18:

// "Нельзя войти"


const ageTask = 17;

const resultTask = ageTask >= 18

    ? "Можно войти"

    : "Нельзя войти";

console.log(resultTask);


// Результат:

// "Нельзя войти"


// --------------------------------------------------

// ЗАДАНИЕ 2 — ПОКУПКА

// --------------------------------------------------

// Если денег хватает:

// "Покупка успешна"

// Если денег не хватает:

// "Недостаточно денег"


const moneyTask = 5000;

const productTask = 3500;

const purchaseTask = moneyTask >= productTask

    ? "Покупка успешна"

    : "Недостаточно денег";

console.log(purchaseTask);


// Результат:

// "Покупка успешна"


// --------------------------------------------------

// ЗАДАНИЕ 3 — ОЦЕНКА

// --------------------------------------------------

// Если score >= 50:

// "Сдал"

// Иначе:

// "Не сдал"


const scoreTask = 75;

const scoreResult = scoreTask >= 50

    ? "Сдал"

    : "Не сдал";

console.log(scoreResult);


// Результат:

// "Сдал"


// --------------------------------------------------

// ЗАДАНИЕ 4 — TRUTHY / FALSY

// --------------------------------------------------

// Если username truthy:

// "Пользователь найден"

// Если username falsy:

// "Пользователь не найден"


const usernameTask = "Hiraoka";

const usernameResult = usernameTask

    ? "Пользователь найден"

    : "Пользователь не найден";

console.log(usernameResult);


// Результат:

// "Пользователь найден"


// --------------------------------------------------

// ЗАДАНИЕ 5 — ПУСТАЯ СТРОКА

// --------------------------------------------------

// Если message truthy:

// "Сообщение есть"

// Если message falsy:

// "Сообщения нет"


const messageTask = "";

const messageResult = messageTask

    ? "Сообщение есть"

    : "Сообщения нет";

console.log(messageResult);


// Результат:

// "Сообщения нет"


// ==================================================

// ДОПОЛНИТЕЛЬНАЯ ПРОВЕРКА ПОНИМАНИЯ

// ==================================================

// НЕОБХОДИМО ПРЕДСКАЗАТЬ РЕЗУЛЬТАТ ДО ЗАПУСКА.


// 1.

const check1 = 10 > 5

    ? "A"

    : "B";

console.log(check1);


// Ответ:

// A


// 2.

const check2 = 10 < 5

    ? "A"

    : "B";

console.log(check2);


// Ответ:

// B


// 3.

const check3 = 0

    ? "A"

    : "B";

console.log(check3);


// Ответ:

// B


// 4.

const check4 = "Hello"

    ? "A"

    : "B";

console.log(check4);


// Ответ:

// A


// 5.

const check5 = ""

    ? "A"

    : "B";

console.log(check5);


// Ответ:

// B


// ==================================================

// ГЛАВНОЕ ИЗ УРОКА

// ==================================================

// ? : — тернарный оператор.


// Он является короткой записью простого if / else.


// Схема:

// условие ? если true : если false


// Пример:

// const result = age >= 18 ? "Да" : "Нет";


// Условие true → "Да"

// Условие false → "Нет"


// Тернарный оператор особенно удобен,

// когда нужно получить значение и сохранить

// его в переменную.


// Если логика становится сложной или вариантов

// больше двух — лучше использовать if / else if / else.
