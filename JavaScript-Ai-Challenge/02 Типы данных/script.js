// =====================================================

// Тип данных говорит JavaScript, какое значение хранится в переменной.

// -----------------------------------------------------
// string - строка
// -----------------------------------------------------

const firstName = "Ali";
const greeting = "Привет";

console.log(greeting + ", " + firstName);

// Строки можно писать в:
// "двойных кавычках"
// 'одинарных кавычках'
// `шаблонных строках`

const city = "Tashkent";
console.log(`Город: ${city}`);

// -----------------------------------------------------
// number - число
// -----------------------------------------------------

const age = 18;
const price = 99.5;

console.log(age);
console.log(price);
console.log(age + price);

// -----------------------------------------------------
// boolean - логическое значение
// -----------------------------------------------------

const isStudent = true;
const isAdmin = false;

console.log(isStudent);
console.log(isAdmin);

// boolean часто используют в условиях.

if (isStudent) {
    console.log("Пользователь студент");
}

// -----------------------------------------------------
// undefined
// -----------------------------------------------------

// undefined значит: переменная создана, но значения пока нет.

let userEmail;
console.log(userEmail); // undefined

// -----------------------------------------------------
// null
// -----------------------------------------------------

// null значит: значения специально нет.

const selectedProduct = null;
console.log(selectedProduct);

// -----------------------------------------------------
// object
// -----------------------------------------------------

// object хранит несколько значений внутри одного объекта.

const user = {
    name: "Madina",
    age: 20,
    isStudent: true
};

console.log(user.name);
console.log(user.age);

// -----------------------------------------------------
// array - массив
// -----------------------------------------------------

// Массив - это список значений.
// В JavaScript массив тоже относится к типу object.

const fruits = ["apple", "banana", "orange"];

console.log(fruits[0]);
console.log(fruits[1]);
console.log(fruits[2]);

// -----------------------------------------------------
// typeof
// -----------------------------------------------------

// typeof показывает тип значения.

console.log(typeof "Hello"); // string
console.log(typeof 123); // number
console.log(typeof true); // boolean
console.log(typeof undefined); // undefined
console.log(typeof null); // object
console.log(typeof { name: "Ali" }); // object

// Важно:
// typeof null показывает object. Это старая особенность JavaScript.

