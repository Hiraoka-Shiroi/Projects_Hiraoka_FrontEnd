// Циклы нужны, чтобы повторять один и тот же код несколько раз.

// -----------------------------------------------------
// Цикл for
// -----------------------------------------------------

// for удобно использовать, когда мы знаем,
// сколько раз нужно повторить действие.

for (let i = 1; i <= 5; i++) {
    console.log("Повтор номер:", i);
}

// Как читать:
// let i = 1  - начальное значение
// i <= 5     - условие работы цикла
// i++        - увеличить i на 1 после каждого круга

// -----------------------------------------------------
// Пример: сумма чисел от 1 до 10
// -----------------------------------------------------

let sum = 0;

for (let i = 1; i <= 10; i++) {
    sum = sum + i;
}

console.log("Сумма от 1 до 10:", sum);

// -----------------------------------------------------
// Цикл while
// -----------------------------------------------------

// while работает, пока условие равно true.

let count = 1;

while (count <= 5) {
    console.log("Счетчик:", count);
    count++;
}

// Важно:
// если забыть count++, цикл может стать бесконечным.

