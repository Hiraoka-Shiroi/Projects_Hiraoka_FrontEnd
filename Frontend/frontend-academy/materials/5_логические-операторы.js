// 1. &&: нужны оба условия

// && читается «И». Для двух boolean результат true получается только тогда, когда слева и справа true. Для письменного упражнения нужна и книга, и ручка: одного условия недостаточно. Сначала разбери все четыре сочетания без if.

console.log(true && true);
console.log(true && false);
console.log(false && true);
console.log(false && false);

// Разбор строк: Строка 1: оба true, вывод true. Строка 2: второе false, вывод false. Строка 3: первое false, вывод false. Строка 4: оба false, вывод false. Только первая строка даёт true.

// 2. ||: достаточно одного

// || читается «ИЛИ»: хотя бы одно условие должно быть true. Если оба true, результат тоже true. Например, вход на встречу разрешён по билету или по списку гостей. Человеку с обоими подтверждениями вход тоже разрешён.

console.log(true || true);
console.log(true || false);
console.log(false || true);
console.log(false || false);

// Разбор строк: Строки 1–3 печатают true: в каждой есть хотя бы одно true. Строка 4 печатает false: оба условия false. Для || одного подходящего варианта достаточно, для && нужны оба.

// 3. !: противоположный boolean

// ! читается «НЕ» и стоит перед одним значением. !true даёт false, !false даёт true. Для имени shopClosed отрицание !shopClosed означает «не закрыто». Сам оператор не меняет исходную переменную; результат можно сохранить отдельно.

const shopClosed = false;
const shopOpen = !shopClosed;
console.log(shopClosed);
console.log(shopOpen);
