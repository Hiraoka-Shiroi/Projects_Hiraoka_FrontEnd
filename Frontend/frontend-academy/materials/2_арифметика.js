/*
1. Оператор и выражение

Оператор обозначает действие над значениями: + складывает, - вычитает, * умножает, / делит. Значения слева и справа называют операндами. 24 + 6 — выражение: JavaScript вычисляет его и получает одно новое значение. Знак = присваивает результат, а не проверяет равенство.

Числовые литералы в этих примерах написаны без кавычек. Строки вроде "24" разберём в уроке 3: они могут изменить поведение +.
*/
const firstAmount = 24;
const secondAmount = 6;
console.log(firstAmount + secondAmount);
console.log(firstAmount - secondAmount);
console.log(firstAmount * secondAmount);
console.log(firstAmount / secondAmount);

/*
ПОСТРОЧНЫЙ РАЗБОР
Строки 1–2 сохраняют два числа. Строка 3 печатает сумму 30. Строка 4 печатает разность 18. Строка 5 печатает произведение 144. Строка 6 печатает частное 4. Исходные firstAmount и secondAmount ни одно из этих выражений не меняет.
*/

/*
2. Остаток и степень

% возвращает остаток от деления; это не знак процента. 17 % 5 равен 2: в 17 помещаются три полные группы по 5 и остаётся 2. Для положительных целых a % b удобно описывать неполную группу. Делитель не должен быть нулём для содержательного остатка.

** возводит в степень: 3 ** 2 означает 3 умножить на 3. Пока используем небольшие положительные числа, чтобы сосредоточиться на смысле операций.
*/
const stickerCount = 17;
const packSize = 5;
const looseStickers = stickerCount % packSize;
console.log(looseStickers);
console.log(3 ** 2);
console.log(20 % 5);

/*
ПОСТРОЧНЫЙ РАЗБОР
Строки 1–2 задают количество и размер пачки. Строка 3 получает остаток 2. Строка 4 его печатает. Строка 5 печатает 9. Строка 6 печатает 0: двадцать делится на пять без остатка.
*/

/*
3. Приоритет и скобки

JavaScript не выполняет все арифметические действия просто слева направо. Сначала раскрывает скобки, затем степени, затем умножение/деление/остаток, потом сложение/вычитание. Для + и - одного приоритета порядок идёт слева направо. В цепочке ** порядок особый; пока ставь скобки явно.

Скобки полезны, когда нужно изменить порядок или подчеркнуть смысл. Цена двух товаров со скидкой на всю сумму требует сначала найти сумму, затем применить дальнейший расчёт.
*/
console.log(8 + 4 * 3);
console.log((8 + 4) * 3);
console.log(30 - 10 - 5);
console.log(30 - (10 - 5));
console.log(2 ** 3 + 1);

/*
ПОСТРОЧНЫЙ РАЗБОР
Строка 1: сначала 4 * 3, затем + 8; вывод 20. Строка 2: сначала 8 + 4, затем * 3; вывод 36. Строка 3: (30 - 10) - 5; вывод 15. Строка 4: сначала 10 - 5; вывод 25. Строка 5: сначала степень 8, затем + 1; вывод 9.
*/

/*
4. Расчёт с понятными промежуточными именами

Разделяй расчёт на значения с предметным смыслом. unitPrice — цена одной единицы, quantity — количество, goodsTotal — стоимость всех единиц. Промежуточное имя помогает проверить действие и единицы измерения.

Выражение balance = balance - spent читает прежний balance справа, вычисляет остаток и только затем записывает новый balance слева. const исходных цен не меняются.
*/
