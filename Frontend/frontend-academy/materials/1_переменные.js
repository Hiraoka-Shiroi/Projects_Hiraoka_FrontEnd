/*
1. Имя, значение и вывод

Переменная связывает выбранное имя со значением. В const learnerName = "Hiraoka"; слово const объявляет переменную, learnerName — её имя, = задаёт начальное значение, а "Hiraoka" — текстовая строка. Кавычки ограничивают текст и не входят в значение. Точка с запятой завершает инструкцию.

console.log(learnerName); показывает значение в терминале. Если написать console.log("learnerName"), появится сам текст learnerName. Компьютер не догадывается, что строка должна означать имя переменной.
*/
