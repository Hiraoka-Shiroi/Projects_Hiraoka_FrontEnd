const learningDirection = "Frontend";
console.log(learnerName);
console.log(learningDirection);

/*
ПОСТРОЧНЫЙ РАЗБОР
Строка 1 сохраняет имя ученика. Строка 2 сохраняет направление. Строка 3 читает learnerName без кавычек и печатает Hiraoka. Строка 4 читает learningDirection и печатает Frontend. Код идёт сверху вниз; вывод имеет две строки.
*/

/*
2. let: объявить один раз, присваивать дальше

let подходит, если позже понадобится другое значение. Объявление создаёт имя: let lessonState = "не начат". Последующее lessonState = "в процессе" меняет значение уже существующей переменной. Во второй строке слово let не повторяют.

Каждый console.log читает значение в момент своего выполнения. Ранний вывод не переписывается задним числом после присваивания.
*/
let lessonState = "не начат";
console.log(lessonState);
lessonState = "в процессе";
console.log(lessonState);

/*
ПОСТРОЧНЫЙ РАЗБОР
Строка 1 создаёт lessonState. Строка 2 печатает не начат. Строка 3 заменяет строку новой. Строка 4 печатает в процессе. Было одно объявление и одно последующее присваивание.
*/

/*
3. const: значение нельзя переприсвоить

Используй const, когда этому имени не требуется новое значение. Для const начальное значение задают сразу: const courseName = "Frontend Academy". Последующее courseName = "Другой курс" вызовет ошибку. const courseName без значения тоже некорректно.

const не делает значение секретным и не запрещает его читать. В этом уроке работаем с простыми строками и числами. Особенности объектов изучаются позже.
*/
const courseName = "Frontend Academy";
console.log(courseName);
// courseName = "Другой курс"; // Не выполнять: переприсваивание const.
// const emptyName; // Не выполнять: отсутствует начальное значение.

/*
ПОСТРОЧНЫЙ РАЗБОР
Строка 1 объявляет const с начальным текстом. Строка 2 показывает этот текст. Строки 3–4 начинаются с //: это комментарии, Node их не выполняет. Поэтому учебный пример запускается целиком. Ошибочные инструкции здесь только обсуждаются.
*/

/*
4. Имена и повторные объявления

Идентификатор — имя переменной. В начале учебных имён используй латинскую букву, далее буквы и цифры; составные имена пиши camelCase: orderState, learningGoal. Имя не должно начинаться с цифры или содержать пробел. Зарезервированные слова вроде const именем не становятся.

Регистр важен: lessonNumber и LessonNumber — разные имена. Повторное const или let с тем же именем в одном файле на одном уровне — синтаксическая ошибка. Такой файл может не выполнить даже первую строку. Для новых примеров выбирай новые имена.
*/
