// Объект хранит данные в формате ключ: значение.

let user = {
    name: "Ali",
    age: 20,
    isStudent: true
};

console.log(user.name);
console.log(user.age);
console.log(user.isStudent);

// Можно менять значение свойства.

user.age = 21;
console.log("Новый возраст:", user.age);

// Можно добавлять новое свойство.

user.city = "Tashkent";
console.log(user);

// -----------------------------------------------------
// Объект внутри функции
// -----------------------------------------------------

function describeUser(person) {
    return person.name + ", возраст: " + person.age;
}

console.log(describeUser(user));

