let students = [
    { name: "Ali", age: 17, grade: 10 },
    { name: "Madina", age: 18, grade: 11 },
    { name: "Sasha", age: 16, grade: 9 }
];

function checkStudent(student) {
    if (student.grade >= 11) {
        return student.name + " может закончить школу";
    } else {
        return student.name + " еще учится";
    }
}

for (let i = 0; i < students.length; i++) {
    console.log(checkStudent(students[i]));
}

