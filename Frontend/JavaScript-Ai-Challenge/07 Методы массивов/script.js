// Методы массивов - это готовые команды для работы с массивами.

let numbers = [1, 2, 3];

numbers.push(4); // добавить элемент в конец
console.log(numbers); // [1, 2, 3, 4]

numbers.pop(); // удалить последний элемент
console.log(numbers); // [1, 2, 3]

numbers.unshift(0); // добавить элемент в начало
console.log(numbers); // [0, 1, 2, 3]

numbers.shift(); // удалить первый элемент
console.log(numbers); // [1, 2, 3]

