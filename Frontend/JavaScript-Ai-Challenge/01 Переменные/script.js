// Переменная - это "коробка", в которой хранится значение.
// В современном JavaScript чаще всего используют let и const.

// let используют, если значение потом будет меняться.

let age = 18;
age = 19;
console.log("Возраст:", age);

// const используют, если значение не нужно переназначать.

const userName = "Hiraoka";
console.log("Имя:", userName);

// Хорошее правило:
// сначала выбирай const, а если значение нужно изменить - используй let.

// -----------------------------------------------------
// Простые вычисления
// -----------------------------------------------------

const numberA = 7;
const numberB = 3;

console.log("Сумма:", numberA + numberB);
console.log("Разность:", numberA - numberB);
console.log("Произведение:", numberA * numberB);
console.log("Деление:", numberA / numberB);

// -----------------------------------------------------
// Короткая запись изменения числа
// -----------------------------------------------------

let count = 0;

count = count + 1;
count += 1;
count++;

console.log("Счетчик:", count); // 3

// -----------------------------------------------------
// Важный момент про const и объекты
// -----------------------------------------------------

const user = {
    name: "Анна",
    age: 25
};

// const запрещает переназначить саму переменную user,
// но не запрещает менять свойства внутри объекта.

user.age = 26;
user.city = "Москва";

console.log(user);

// Так делать нельзя:
// user = {};
// Будет ошибка, потому что const нельзя переназначать.

// -----------------------------------------------------
// Копия значения и ссылка на объект
// -----------------------------------------------------

let firstNumber = 5;
let secondNumber = firstNumber;

firstNumber = 10;

console.log(firstNumber); // 10
console.log(secondNumber); // 5

// Числа, строки и boolean копируются как отдельные значения.

const firstObject = { value: 5 };
const secondObject = firstObject;

secondObject.value = 10;

console.log(firstObject.value); // 10
console.log(secondObject.value); // 10

// Объекты передаются по ссылке.
// firstObject и secondObject смотрят на один и тот же объект.

