// Условия нужны, чтобы выполнять разный код
// в зависимости от ситуации.

// -----------------------------------------------------
// if / else
// -----------------------------------------------------

const age = 18;

if (age >= 18) {
    console.log("Доступ разрешен");
} else {
    console.log("Доступ запрещен");
}

// Если условие в круглых скобках true,
// выполнится первый блок.
// Если false - выполнится блок else.

// -----------------------------------------------------
// Сравнения
// -----------------------------------------------------

const number = 5;

if (number > 0) {
    console.log("Число положительное");
} else if (number < 0) {
    console.log("Число отрицательное");
} else {
    console.log("Число равно нулю");
}

// Частые операторы сравнения:
// >   больше
// <   меньше
// >=  больше или равно
// <=  меньше или равно
// === строго равно
// !== строго не равно

// -----------------------------------------------------
// boolean в условии
// -----------------------------------------------------

const isRaining = true;

if (isRaining) {
    console.log("Возьми зонт");
} else {
    console.log("Можно идти без зонта");
}

// -----------------------------------------------------
// else if
// -----------------------------------------------------

const score = 85;

if (score >= 90) {
    console.log("Оценка: отлично");
} else if (score >= 60) {
    console.log("Оценка: хорошо");
} else {
    console.log("Оценка: нужно повторить тему");
}

// -----------------------------------------------------
// Логические операторы
// -----------------------------------------------------

const hasTicket = true;
const hasPassport = true;

if (hasTicket && hasPassport) {
    console.log("Можно пройти на посадку");
} else {
    console.log("Нужно проверить документы");
}

// && значит "и": оба условия должны быть true.
// || значит "или": хотя бы одно условие должно быть true.
// ! значит "не": меняет true на false и наоборот.

const isWeekend = false;
const isHoliday = true;

if (isWeekend || isHoliday) {
    console.log("Можно отдохнуть");
} else {
    console.log("Рабочий день");
}

